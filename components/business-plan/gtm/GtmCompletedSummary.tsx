'use client'

import React, { useState } from 'react'
import { GtmStrategyFormData } from '@/lib/gtm-types'
import { SummaryCard } from './SummaryCard'
import { Button } from '@/components/ui/button'
import { Badge } from '@/components/ui/badge'
import { toast } from 'sonner'
import {
  Edit3,
  Download,
  Printer,
  Copy,
  Send,
  Building,
  Mail,
  User,
  Calendar,
  CheckCircle2,
  ExternalLink,
  FileSpreadsheet,
  Check,
  Globe,
  Briefcase,
  Users,
  Target,
  MessageSquare,
  PhoneCall,
  CalendarDays,
  ShieldCheck,
  Video
} from 'lucide-react'

interface GtmCompletedSummaryProps {
  data: GtmStrategyFormData
  onEdit: () => void
}

export function GtmCompletedSummary({ data, onEdit }: GtmCompletedSummaryProps) {
  const [isSubmitting, setIsSubmitting] = useState(false)
  const [submittedId, setSubmittedId] = useState<string | null>(null)
  const [copied, setCopied] = useState(false)

  // 1. Submit to Backend API
  const handleSubmitBackend = async () => {
    setIsSubmitting(true)
    try {
      const res = await fetch('/api/gtm-submissions', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(data)
      })

      if (!res.ok) throw new Error('Submission endpoint returned an error')

      const result = await res.json()
      setSubmittedId(result.submissionId || 'GTM-SYNCED')
      toast.success('GTM Strategy successfully synced with CoreConnect backend!', {
        description: `Submission Reference ID: ${result.submissionId}`
      })
    } catch (err) {
      console.error(err)
      toast.error('Could not connect to backend endpoint. Draft remains safely stored in local state.')
    } finally {
      setIsSubmitting(false)
    }
  }

  // 2. Print or Download PDF
  const handlePrint = () => {
    window.print()
  }

  // 3. Copy as formatted text / Markdown
  const handleCopyText = () => {
    const textLines: string[] = [
      `# IDEAL CUSTOMER PROFILE & GO-TO-MARKET STRATEGY`,
      `Company: ${data.companyName || 'N/A'}`,
      `Contact Person: ${data.contactPerson || 'N/A'}`,
      `Email: ${data.email || 'N/A'}`,
      `Strategy Date: ${data.date || 'N/A'}`,
      `Generated by CoreConnect V2`,
      `--------------------------------------------------`,
      ``,
      `## 1. PRODUCTS / SERVICES`,
      `Selected: ${data.products.selectedProducts.join(', ') || 'None'}${data.products.otherProduct ? ` (Other: ${data.products.otherProduct})` : ''}`,
      `Collaterals Available: ${data.products.hasCollaterals ? 'Yes' : 'No'}`,
      data.products.hasCollaterals ? `Details: ${data.products.collateralsDetails}` : '',
      ``,
      `## 2. GEOGRAPHICAL LOCATIONS`,
      `Country: ${data.geography.country}`,
      ...data.geography.regions
        .slice()
        .sort((a, b) => (a.priority || 99) - (b.priority || 99))
        .map((r) => `- [Priority #${r.priority || 'Unassigned'}] ${r.name}`),
      ``,
      `## 3. TARGET INDUSTRY`,
      data.industry.subContractors.selected
        ? `- [Priority #${data.industry.subContractors.priority || 'Unassigned'}] Sub-Contractors: ${data.industry.subContractors.trades.join(', ')}`
        : '',
      data.industry.generalContractors.selected
        ? `- [Priority #${data.industry.generalContractors.priority || 'Unassigned'}] General Contractors`
        : '',
      data.industry.otherIndustry.selected
        ? `- [Priority #${data.industry.otherIndustry.priority || 'Unassigned'}] Other Industry: ${data.industry.otherIndustry.name}`
        : '',
      data.industry.targetStartDate ? `Targeting Start Date: ${data.industry.targetStartDate}` : '',
      ``,
      `## 4. COMPANY SIZE (${data.companySize.basis.toUpperCase()})`,
      ...data.companySize.options
        .filter((o) => o.selected)
        .sort((a, b) => (a.priority || 99) - (b.priority || 99))
        .map((o) => `- [Priority #${o.priority || 'Unassigned'}] ${o.label}${o.customRange ? `: ${o.customRange}` : ''}`),
      ``,
      `## 5. TARGET JOB TITLES`,
      `Titles: ${[...data.jobTitles.selectedTitles, ...data.jobTitles.customTitles].join(', ')}`,
      ``,
      `## 6. FOCUSED ACCOUNTS`,
      data.focusedAccounts.decideLater
        ? `Status: Decide Later`
        : data.focusedAccounts.accounts.map((a) => `- ${a.companyName}: ${a.comments} | Target Projects: ${a.targetProjects}`).join('\n'),
      ``,
      `## 7. OUTREACH STRATEGY`,
      data.outreach.email.enabled ? `- Email: ${data.outreach.email.details}` : '',
      data.outreach.linkedIn.enabled ? `- LinkedIn: ${data.outreach.linkedIn.details}` : '',
      data.outreach.calls.enabled ? `- Calls: ${data.outreach.calls.details}` : '',
      ``,
      `## 8. CONFERENCES / TRADE SHOWS`,
      `Request Research Support: ${data.conferences.requestResearchSupport ? 'Yes' : 'No'}`,
      ...data.conferences.conferences.map((c) => `- ${c.eventName} (${c.date}, ${c.location}) - Notes: ${c.notes}`),
      ``,
      `## 9. OTHERS / STRATEGIC NOTES`,
      data.otherNotes || 'None',
      ``,
      `## 10. CRM & TECH STACK`,
      `Uses CRM: ${data.crm.usesCrm ? `Yes (${data.crm.crmProvider})` : 'No'}`,
      data.crm.usesCrm && data.crm.crmDetails ? `CRM Details: ${data.crm.crmDetails}` : '',
      ``,
      `## 11. WEEKLY MEETING CADENCE`,
      `Scheduled: Every ${data.weeklyMeeting.day} at ${data.weeklyMeeting.time} (${data.weeklyMeeting.timeZone})`,
      ``,
      `## 12. POINT OF CONTACT`,
      ...data.pointOfContact.contacts.map((c) => `- ${c.name} (${c.role}) | Email: ${c.email} | Phone: ${c.phone}`),
      ``,
      `## 13. MODE OF COMMUNICATION`,
      `Channels: ${data.communication.selectedModes.join(', ')}${data.communication.otherMode ? ` (${data.communication.otherMode})` : ''}`
    ]
      .filter((line) => line !== '')
      .join('\n')

    navigator.clipboard.writeText(textLines)
    setCopied(true)
    toast.success('Strategy copied to clipboard as formatted text!')
    setTimeout(() => setCopied(false), 3000)
  }

  // 4. Download as CSV / Excel matching internal ICP spreadsheet format
  const handleDownloadCsv = () => {
    const rows: string[][] = [
      ['Section', 'Item / Category', 'Priority', 'Details / Sub-options'],
      ['HEADER', 'Company Name', '', data.companyName],
      ['HEADER', 'Contact Person', '', data.contactPerson],
      ['HEADER', 'Email', '', data.email],
      ['HEADER', 'Strategy Date', '', data.date],

      // Section 1: Products
      ['1. PRODUCTS / SERVICES', 'Selected Products', '', data.products.selectedProducts.join('; ') + (data.products.otherProduct ? ` (Other: ${data.products.otherProduct})` : '')],
      ['1. PRODUCTS / SERVICES', 'Collaterals Available', '', data.products.hasCollaterals ? `Yes: ${data.products.collateralsDetails}` : 'No'],

      // Section 2: Geography (sorted by priority)
      ...data.geography.regions
        .slice()
        .sort((a, b) => (a.priority || 99) - (b.priority || 99))
        .map((r) => ['2. GEOGRAPHICAL LOCATIONS', `${data.geography.country} - ${r.name}`, String(r.priority || ''), '']),

      // Section 3: Industry
      ...(data.industry.subContractors.selected
        ? [['3. TARGET INDUSTRY', 'Sub-Contractors', String(data.industry.subContractors.priority || ''), data.industry.subContractors.trades.join(', ') + (data.industry.subContractors.otherTrade ? ` (${data.industry.subContractors.otherTrade})` : '')]]
        : []),
      ...(data.industry.generalContractors.selected
        ? [['3. TARGET INDUSTRY', 'General Contractors', String(data.industry.generalContractors.priority || ''), 'Turnkey Commercial & Institutional']]
        : []),
      ...(data.industry.otherIndustry.selected
        ? [['3. TARGET INDUSTRY', data.industry.otherIndustry.name || 'Other Industry', String(data.industry.otherIndustry.priority || ''), '']]
        : []),
      ...(data.industry.targetStartDate
        ? [['3. TARGET INDUSTRY', 'Target Start Date', '', data.industry.targetStartDate]]
        : []),

      // Section 4: Company Size
      ...data.companySize.options
        .filter((o) => o.selected)
        .sort((a, b) => (a.priority || 99) - (b.priority || 99))
        .map((o) => ['4. COMPANY SIZE', `Basis: ${data.companySize.basis} - ${o.label}`, String(o.priority || ''), o.customRange || '']),

      // Section 5: Target Job Titles
      ['5. TARGET JOB TITLES', 'Job Titles', '', [...data.jobTitles.selectedTitles, ...data.jobTitles.customTitles].join('; ')],

      // Section 6: Focused Accounts
      ...(data.focusedAccounts.decideLater
        ? [['6. FOCUSED ACCOUNTS', 'Decide Later', '', 'Client requested to review and assign focused accounts at a later stage']]
        : data.focusedAccounts.accounts.map((acc) => [
            '6. FOCUSED ACCOUNTS',
            acc.companyName,
            '',
            `Comments: ${acc.comments} | Target Projects: ${acc.targetProjects}`
          ])),

      // Section 7: Outreach
      ...(data.outreach.email.enabled ? [['7. OUTREACH STRATEGY', 'Email Cadence', '', data.outreach.email.details]] : []),
      ...(data.outreach.linkedIn.enabled ? [['7. OUTREACH STRATEGY', 'LinkedIn Social Selling', '', data.outreach.linkedIn.details]] : []),
      ...(data.outreach.calls.enabled ? [['7. OUTREACH STRATEGY', 'Direct Calls', '', data.outreach.calls.details]] : []),

      // Section 8: Conferences
      ...(data.conferences.requestResearchSupport
        ? [['8. CONFERENCES', 'Research Support Request', '', 'Client requested research support from CoreConnect team']]
        : []),
      ...data.conferences.conferences.map((c) => [
        '8. CONFERENCES',
        c.eventName,
        '',
        `Date: ${c.date} | Location: ${c.location} | Notes: ${c.notes}`
      ]),

      // Section 9: Others
      ['9. OTHERS', 'Strategic Context & Notes', '', data.otherNotes || 'N/A'],

      // Section 10: CRM
      ['10. CRM', data.crm.usesCrm ? `Yes - ${data.crm.crmProvider}` : 'No CRM', '', data.crm.crmDetails || ''],

      // Section 11: Weekly Meeting
      ['11. WEEKLY MEETING', `Every ${data.weeklyMeeting.day} at ${data.weeklyMeeting.time}`, '', data.weeklyMeeting.timeZone],

      // Section 12: Point of Contact
      ...data.pointOfContact.contacts.map((c) => [
        '12. POINT OF CONTACT',
        `${c.name} (${c.role})`,
        '',
        `Email: ${c.email} | Phone: ${c.phone}`
      ]),

      // Section 13: Mode of Communication
      ['13. MODE OF COMMUNICATION', data.communication.selectedModes.join(', ') + (data.communication.otherMode ? ` (${data.communication.otherMode})` : ''), '', '']
    ]

    const csvContent = rows
      .map((row) => row.map((cell) => `"${String(cell ?? '').replace(/"/g, '""')}"`).join(','))
      .join('\n')

    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' })
    const url = URL.createObjectURL(blob)
    const link = document.createElement('a')
    link.href = url
    link.setAttribute('download', `${(data.companyName || 'CoreConnect').replace(/\s+/g, '_')}_GTM_Strategy.csv`)
    document.body.appendChild(link)
    link.click()
    document.body.removeChild(link)
    URL.revokeObjectURL(url)

    toast.success('GTM Strategy spreadsheet exported as CSV!')
  }

  // Sorted regions by priority
  const sortedRegions = [...data.geography.regions].sort((a, b) => (a.priority || 99) - (b.priority || 99))

  // Sorted company sizes by priority
  const sortedSizes = data.companySize.options
    .filter((o) => o.selected)
    .sort((a, b) => (a.priority || 99) - (b.priority || 99))

  return (
    <div className="flex flex-col gap-6 print:m-0 print:p-0">
      {/* Action Bar (Hidden when printing) */}
      <div className="flex flex-wrap items-center justify-between gap-3 rounded-xl border border-slate-200 bg-white p-4 shadow-xs dark:border-slate-800 dark:bg-slate-900 print:hidden">
        <div className="flex items-center gap-2">
          <Badge className="bg-[#10B981] text-white hover:bg-[#10B981] gap-1 px-2.5 py-1 text-xs">
            <CheckCircle2 className="size-3.5" />
            Strategy Generated
          </Badge>
          <span className="text-xs text-slate-500">
            Read-only strategy summary ready for review and export.
          </span>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={onEdit}
            className="gap-1.5 text-xs text-[#0B1F5C] hover:bg-blue-50 dark:text-blue-300 dark:hover:bg-slate-800"
          >
            <Edit3 className="size-3.5" />
            Edit answers
          </Button>

          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={handleCopyText}
            className="gap-1.5 text-xs"
          >
            {copied ? <Check className="size-3.5 text-emerald-600" /> : <Copy className="size-3.5" />}
            {copied ? 'Copied' : 'Copy as text'}
          </Button>

          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={handleDownloadCsv}
            className="gap-1.5 text-xs"
          >
            <FileSpreadsheet className="size-3.5 text-emerald-600" />
            Download as Excel/CSV
          </Button>

          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={handlePrint}
            className="gap-1.5 text-xs"
          >
            <Printer className="size-3.5 text-slate-600 dark:text-slate-300" />
            Print / PDF
          </Button>

          <Button
            type="button"
            size="sm"
            onClick={handleSubmitBackend}
            disabled={isSubmitting}
            className="gap-1.5 bg-[#0B1F5C] text-xs font-semibold text-white hover:bg-[#152e7a] dark:bg-blue-600 dark:hover:bg-blue-700"
          >
            <Send className="size-3.5" />
            {isSubmitting ? 'Syncing...' : submittedId ? 'Synced with API' : 'Submit Strategy'}
          </Button>
        </div>
      </div>

      {/* Strategy Document Container */}
      <div className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm dark:border-slate-800 dark:bg-slate-900 sm:p-8 print:border-none print:shadow-none print:p-0">
        {/* Document Header */}
        <div className="border-b border-slate-200 pb-6 dark:border-slate-800">
          <div className="flex flex-wrap items-start justify-between gap-4">
            <div>
              <div className="flex items-center gap-2">
                <span className="text-xs font-extrabold uppercase tracking-widest text-[#FFC000]">
                  CoreConnect Go-To-Market Blueprint
                </span>
                {submittedId && (
                  <Badge variant="outline" className="border-emerald-300 bg-emerald-50 text-[10px] text-emerald-700 dark:bg-emerald-950/40 dark:text-emerald-300">
                    Ref: {submittedId}
                  </Badge>
                )}
              </div>
              <h1 className="mt-1 text-2xl font-black tracking-tight text-[#0B1F5C] dark:text-white sm:text-3xl">
                {data.companyName || 'Target Client ICP & GTM Strategy'}
              </h1>
              <p className="mt-1 text-xs text-slate-500 dark:text-slate-400">
                Strategic target market parameters, sales channel cadence, and account governance protocol.
              </p>
            </div>

            {/* Document Metadata Badges */}
            <div className="grid grid-cols-2 gap-2 text-xs sm:flex sm:items-center sm:gap-4">
              {data.contactPerson && (
                <div className="flex items-center gap-1.5 rounded-lg border border-slate-100 bg-slate-50 px-3 py-2 dark:border-slate-800 dark:bg-slate-800/50">
                  <User className="size-3.5 text-[#0B1F5C] dark:text-blue-400" />
                  <div>
                    <div className="text-[10px] text-slate-400">Contact Person</div>
                    <div className="font-semibold text-slate-800 dark:text-slate-200">{data.contactPerson}</div>
                  </div>
                </div>
              )}

              {data.email && (
                <div className="flex items-center gap-1.5 rounded-lg border border-slate-100 bg-slate-50 px-3 py-2 dark:border-slate-800 dark:bg-slate-800/50">
                  <Mail className="size-3.5 text-[#0B1F5C] dark:text-blue-400" />
                  <div>
                    <div className="text-[10px] text-slate-400">Email Address</div>
                    <div className="font-semibold text-slate-800 dark:text-slate-200">{data.email}</div>
                  </div>
                </div>
              )}

              <div className="flex items-center gap-1.5 rounded-lg border border-slate-100 bg-slate-50 px-3 py-2 dark:border-slate-800 dark:bg-slate-800/50">
                <Calendar className="size-3.5 text-[#0B1F5C] dark:text-blue-400" />
                <div>
                  <div className="text-[10px] text-slate-400">Effective Date</div>
                  <div className="font-semibold text-slate-800 dark:text-slate-200">{data.date}</div>
                </div>
              </div>
            </div>
          </div>
        </div>

        {/* Strategy Sections Grid */}
        <div className="mt-6 grid gap-5 lg:grid-cols-2">
          {/* SECTION 1: PRODUCTS / SERVICES */}
          {data.products.selectedProducts.length > 0 && (
            <SummaryCard sectionNumber="1" title="Products & Services Offering">
              <div className="flex flex-col gap-3">
                <div className="flex flex-wrap gap-1.5">
                  {data.products.selectedProducts.map((p) => (
                    <Badge key={p} variant="secondary" className="bg-blue-50 text-[#0B1F5C] dark:bg-blue-950/60 dark:text-blue-300">
                      {p}
                    </Badge>
                  ))}
                  {data.products.otherProduct && (
                    <Badge variant="outline" className="border-blue-300 text-blue-700">
                      Other: {data.products.otherProduct}
                    </Badge>
                  )}
                </div>

                <div className="rounded-lg border border-slate-100 bg-slate-50/80 p-3 text-xs dark:border-slate-800 dark:bg-slate-900/50">
                  <div className="font-semibold text-slate-700 dark:text-slate-200">
                    Collaterals Available: {data.products.hasCollaterals ? 'Yes' : 'No'}
                  </div>
                  {data.products.hasCollaterals && data.products.collateralsDetails && (
                    <p className="mt-1 text-slate-600 dark:text-slate-400">
                      {data.products.collateralsDetails}
                    </p>
                  )}
                </div>
              </div>
            </SummaryCard>
          )}

          {/* SECTION 2: GEOGRAPHICAL LOCATIONS (Sorted by Priority) */}
          {sortedRegions.length > 0 && (
            <SummaryCard sectionNumber="2" title={`Target Geography (${data.geography.country})`}>
              <div className="flex flex-col gap-2">
                <div className="text-xs font-semibold text-slate-500">
                  Prioritized Operating Regions:
                </div>
                <div className="flex flex-col gap-1.5">
                  {sortedRegions.map((reg) => (
                    <div
                      key={reg.id}
                      className="flex items-center justify-between rounded-lg border border-slate-100 bg-white p-2.5 text-xs shadow-2xs dark:border-slate-800 dark:bg-slate-800/40"
                    >
                      <span className="font-medium text-slate-800 dark:text-slate-200">
                        {reg.name}
                      </span>
                      {reg.priority != null ? (
                        <Badge className="bg-[#0B1F5C] text-white text-[10px] dark:bg-blue-600">
                          Priority #{reg.priority}
                        </Badge>
                      ) : (
                        <span className="text-[11px] text-slate-400">No priority</span>
                      )}
                    </div>
                  ))}
                </div>
              </div>
            </SummaryCard>
          )}

          {/* SECTION 3: TARGET INDUSTRY */}
          {(data.industry.subContractors.selected || data.industry.generalContractors.selected || data.industry.otherIndustry.selected) && (
            <SummaryCard sectionNumber="3" title="Target Industry Focus">
              <div className="flex flex-col gap-3">
                {data.industry.subContractors.selected && (
                  <div className="rounded-lg border border-slate-100 bg-slate-50/70 p-3 text-xs dark:border-slate-800 dark:bg-slate-900/50">
                    <div className="flex items-center justify-between font-semibold text-slate-800 dark:text-slate-200">
                      <span>Sub-Contractors</span>
                      {data.industry.subContractors.priority && (
                        <Badge className="bg-[#0B1F5C] text-white text-[10px]">
                          Priority #{data.industry.subContractors.priority}
                        </Badge>
                      )}
                    </div>
                    <div className="mt-2 flex flex-wrap gap-1">
                      {data.industry.subContractors.trades.map((t) => (
                        <Badge key={t} variant="secondary" className="text-[11px]">
                          {t}
                        </Badge>
                      ))}
                      {data.industry.subContractors.otherTrade && (
                        <Badge variant="outline" className="text-[11px]">
                          {data.industry.subContractors.otherTrade}
                        </Badge>
                      )}
                    </div>
                  </div>
                )}

                {data.industry.generalContractors.selected && (
                  <div className="flex items-center justify-between rounded-lg border border-slate-100 bg-slate-50/70 p-3 text-xs dark:border-slate-800 dark:bg-slate-900/50">
                    <span className="font-semibold text-slate-800 dark:text-slate-200">General Contractors</span>
                    {data.industry.generalContractors.priority && (
                      <Badge className="bg-[#0B1F5C] text-white text-[10px]">
                        Priority #{data.industry.generalContractors.priority}
                      </Badge>
                    )}
                  </div>
                )}

                {data.industry.otherIndustry.selected && (
                  <div className="flex items-center justify-between rounded-lg border border-slate-100 bg-slate-50/70 p-3 text-xs dark:border-slate-800 dark:bg-slate-900/50">
                    <span className="font-semibold text-slate-800 dark:text-slate-200">
                      {data.industry.otherIndustry.name || 'Other Industry'}
                    </span>
                    {data.industry.otherIndustry.priority && (
                      <Badge className="bg-[#0B1F5C] text-white text-[10px]">
                        Priority #{data.industry.otherIndustry.priority}
                      </Badge>
                    )}
                  </div>
                )}

                {data.industry.targetStartDate && (
                  <div className="text-[11px] text-slate-500">
                    Target Start Date: <span className="font-semibold text-slate-700 dark:text-slate-300">{data.industry.targetStartDate}</span>
                  </div>
                )}
              </div>
            </SummaryCard>
          )}

          {/* SECTION 4: COMPANY SIZE (Sorted by Priority) */}
          {sortedSizes.length > 0 && (
            <SummaryCard sectionNumber="4" title={`Target Company Size (${data.companySize.basis === 'revenue' ? 'Revenue' : 'Employee Count'})`}>
              <div className="flex flex-col gap-2">
                <div className="flex flex-col gap-1.5">
                  {sortedSizes.map((sz) => (
                    <div
                      key={sz.id}
                      className="flex items-center justify-between rounded-lg border border-slate-100 bg-white p-2.5 text-xs shadow-2xs dark:border-slate-800 dark:bg-slate-800/40"
                    >
                      <span className="font-medium text-slate-800 dark:text-slate-200">
                        {sz.label} {sz.customRange ? `(${sz.customRange})` : ''}
                      </span>
                      {sz.priority != null ? (
                        <Badge className="bg-[#0B1F5C] text-white text-[10px]">
                          Priority #{sz.priority}
                        </Badge>
                      ) : (
                        <span className="text-[11px] text-slate-400">No priority</span>
                      )}
                    </div>
                  ))}
                </div>
              </div>
            </SummaryCard>
          )}

          {/* SECTION 5: TARGET JOB TITLES */}
          {(data.jobTitles.selectedTitles.length > 0 || data.jobTitles.customTitles.length > 0) && (
            <SummaryCard sectionNumber="5" title="Target Job Titles & Decision Makers">
              <div className="flex flex-wrap gap-1.5">
                {[...data.jobTitles.selectedTitles, ...data.jobTitles.customTitles].map((title) => (
                  <Badge key={title} variant="secondary" className="bg-slate-100 text-slate-800 dark:bg-slate-800 dark:text-slate-200">
                    {title}
                  </Badge>
                ))}
              </div>
            </SummaryCard>
          )}

          {/* SECTION 6: FOCUSED ACCOUNTS / CUSTOMERS */}
          <SummaryCard sectionNumber="6" title="Focused Accounts & Named Clients">
            {data.focusedAccounts.decideLater ? (
              <div className="rounded-lg border border-dashed border-amber-200 bg-amber-50/50 p-3 text-xs text-amber-800 dark:border-amber-900/60 dark:bg-amber-950/20 dark:text-amber-300">
                Client elected to decide focused accounts at a later review stage.
              </div>
            ) : data.focusedAccounts.accounts.length === 0 ? (
              <div className="text-xs text-slate-400 italic">No focused accounts listed.</div>
            ) : (
              <div className="overflow-x-auto rounded-lg border border-slate-100 dark:border-slate-800">
                <table className="w-full text-left text-xs">
                  <thead className="bg-slate-50 font-semibold text-slate-700 dark:bg-slate-900/80 dark:text-slate-300">
                    <tr>
                      <th className="px-3 py-2">Company</th>
                      <th className="px-3 py-2">Comments</th>
                      <th className="px-3 py-2">Target Projects</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                    {data.focusedAccounts.accounts.map((acc) => (
                      <tr key={acc.id}>
                        <td className="px-3 py-2 font-medium text-[#0B1F5C] dark:text-blue-300">{acc.companyName}</td>
                        <td className="px-3 py-2 text-slate-600 dark:text-slate-400">{acc.comments || '—'}</td>
                        <td className="px-3 py-2 text-slate-600 dark:text-slate-400">{acc.targetProjects || '—'}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </SummaryCard>

          {/* SECTION 7: OUTREACH STRATEGY */}
          {(data.outreach.email.enabled || data.outreach.linkedIn.enabled || data.outreach.calls.enabled) && (
            <SummaryCard sectionNumber="7" title="Active Outreach Channels">
              <div className="flex flex-col gap-2.5">
                {data.outreach.email.enabled && (
                  <div className="rounded-lg border border-slate-100 bg-slate-50/60 p-2.5 text-xs dark:border-slate-800 dark:bg-slate-900/40">
                    <div className="flex items-center gap-1.5 font-bold text-[#0B1F5C] dark:text-blue-300">
                      <Mail className="size-3.5" />
                      Email Outreach
                    </div>
                    <p className="mt-1 text-slate-600 dark:text-slate-400">{data.outreach.email.details || 'Default 3-touch cadence'}</p>
                  </div>
                )}

                {data.outreach.linkedIn.enabled && (
                  <div className="rounded-lg border border-slate-100 bg-slate-50/60 p-2.5 text-xs dark:border-slate-800 dark:bg-slate-900/40">
                    <div className="flex items-center gap-1.5 font-bold text-[#0B1F5C] dark:text-blue-300">
                      <Globe className="size-3.5" />
                      LinkedIn Social Selling
                    </div>
                    <p className="mt-1 text-slate-600 dark:text-slate-400">{data.outreach.linkedIn.details || 'Connection requests + content sharing'}</p>
                  </div>
                )}

                {data.outreach.calls.enabled && (
                  <div className="rounded-lg border border-slate-100 bg-slate-50/60 p-2.5 text-xs dark:border-slate-800 dark:bg-slate-900/40">
                    <div className="flex items-center gap-1.5 font-bold text-[#0B1F5C] dark:text-blue-300">
                      <PhoneCall className="size-3.5" />
                      Direct Calling Cadence
                    </div>
                    <p className="mt-1 text-slate-600 dark:text-slate-400">{data.outreach.calls.details || 'Targeted phone outreach'}</p>
                  </div>
                )}
              </div>
            </SummaryCard>
          )}

          {/* SECTION 8: CONFERENCES & TRADE SHOWS */}
          <SummaryCard sectionNumber="8" title="Conferences & Trade Shows">
            <div className="flex flex-col gap-3">
              {data.conferences.requestResearchSupport && (
                <div className="flex items-center gap-2 rounded-lg bg-blue-50/80 px-3 py-2 text-xs font-semibold text-[#0B1F5C] dark:bg-blue-950/40 dark:text-blue-300">
                  <CheckCircle2 className="size-3.5 text-emerald-600" />
                  Client requested research support from CoreConnect team.
                </div>
              )}

              {data.conferences.conferences.length > 0 ? (
                <div className="overflow-x-auto rounded-lg border border-slate-100 dark:border-slate-800">
                  <table className="w-full text-left text-xs">
                    <thead className="bg-slate-50 font-semibold text-slate-700 dark:bg-slate-900/80 dark:text-slate-300">
                      <tr>
                        <th className="px-3 py-2">Event</th>
                        <th className="px-3 py-2">Date</th>
                        <th className="px-3 py-2">Location</th>
                        <th className="px-3 py-2">Notes</th>
                      </tr>
                    </thead>
                    <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                      {data.conferences.conferences.map((conf) => (
                        <tr key={conf.id}>
                          <td className="px-3 py-2 font-medium text-slate-800 dark:text-slate-200">{conf.eventName}</td>
                          <td className="px-3 py-2 text-slate-600 dark:text-slate-400">{conf.date || '—'}</td>
                          <td className="px-3 py-2 text-slate-600 dark:text-slate-400">{conf.location || '—'}</td>
                          <td className="px-3 py-2 text-slate-600 dark:text-slate-400">{conf.notes || '—'}</td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              ) : (
                <div className="text-xs text-slate-400 italic">No specific conferences recorded yet.</div>
              )}
            </div>
          </SummaryCard>

          {/* SECTION 9: OTHERS / STRATEGIC NOTES */}
          {data.otherNotes && (
            <SummaryCard sectionNumber="9" title="Strategic Notes & Considerations">
              <p className="text-xs text-slate-700 whitespace-pre-line dark:text-slate-300">
                {data.otherNotes}
              </p>
            </SummaryCard>
          )}

          {/* SECTION 10: CRM */}
          <SummaryCard sectionNumber="10" title="CRM & Pipeline Infrastructure">
            <div className="text-xs">
              <div className="font-semibold text-slate-800 dark:text-slate-200">
                CRM Platform: {data.crm.usesCrm ? data.crm.crmProvider : 'No CRM in use'}
              </div>
              {data.crm.usesCrm && data.crm.crmDetails && (
                <p className="mt-1 text-slate-600 dark:text-slate-400">{data.crm.crmDetails}</p>
              )}
            </div>
          </SummaryCard>

          {/* SECTION 11: WEEKLY MEETING CADENCE */}
          <SummaryCard sectionNumber="11" title="Account Governance Cadence">
            <div className="flex items-center gap-3 rounded-lg border border-slate-100 bg-slate-50/70 p-3 text-xs dark:border-slate-800 dark:bg-slate-900/50">
              <CalendarDays className="size-5 text-[#FFC000]" />
              <div>
                <div className="font-bold text-[#0B1F5C] dark:text-white">
                  Every {data.weeklyMeeting.day} at {data.weeklyMeeting.time}
                </div>
                <div className="text-[11px] text-slate-500">
                  Time Zone: {data.weeklyMeeting.timeZone}
                </div>
              </div>
            </div>
          </SummaryCard>

          {/* SECTION 12: POINT OF CONTACT */}
          {data.pointOfContact.contacts.length > 0 && (
            <SummaryCard sectionNumber="12" title="Designated Points of Contact">
              <div className="flex flex-col gap-2">
                {data.pointOfContact.contacts.map((c) => (
                  <div
                    key={c.id}
                    className="flex flex-wrap items-center justify-between gap-2 rounded-lg border border-slate-100 bg-white p-2.5 text-xs shadow-2xs dark:border-slate-800 dark:bg-slate-800/40"
                  >
                    <div>
                      <div className="font-bold text-slate-800 dark:text-slate-200">{c.name || 'Unnamed Contact'}</div>
                      <div className="text-[11px] text-slate-500">{c.role || 'Primary Contact'}</div>
                    </div>
                    <div className="text-right text-[11px] text-slate-600 dark:text-slate-400">
                      <div>{c.email || '—'}</div>
                      <div>{c.phone || '—'}</div>
                    </div>
                  </div>
                ))}
              </div>
            </SummaryCard>
          )}

          {/* SECTION 13: MODE OF COMMUNICATION */}
          {data.communication.selectedModes.length > 0 && (
            <SummaryCard sectionNumber="13" title="Preferred Communication Modes">
              <div className="flex flex-wrap gap-1.5">
                {data.communication.selectedModes.map((mode) => (
                  <Badge key={mode} variant="secondary" className="bg-emerald-50 text-emerald-800 dark:bg-emerald-950/50 dark:text-emerald-300">
                    {mode}
                  </Badge>
                ))}
                {data.communication.otherMode && (
                  <Badge variant="outline" className="border-emerald-300 text-emerald-700">
                    Other: {data.communication.otherMode}
                  </Badge>
                )}
              </div>
            </SummaryCard>
          )}
        </div>
      </div>
    </div>
  )
}
